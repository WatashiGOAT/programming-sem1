#include <stdio.h>

int main(void) {
    double m1, m2, r, F;
    const double G = 6.674e-11; // Гравітаційна стала

    printf("=== Закон всесвітнього тяжіння ===\n");
    
    printf("Введіть масу першого тіла m1 (кг): ");
    if (scanf("%lf", &m1) != 1 || m1 <= 0) {
        printf("Помилка: маса повинна бути додатним числом!\n");
        return 1;
    }

    printf("Введіть масу другого тіла m2 (кг): ");
    if (scanf("%lf", &m2) != 1 || m2 <= 0) {
        printf("Помилка: маса повинна бути додатним числом!\n");
        return 1;
    }

    printf("Введіть відстань між тілами r (м): ");
    if (scanf("%lf", &r) != 1 || r <= 0) {
        printf("Помилка: відстань має бути більше 0 (захист від ділення на нуль)!\n");
        return 1;
    }

    // Обчислення сили взаємодії
    F = G * (m1 * m2) / (r * r);

    printf("\nРезультат:\n");
    printf("Сила гравітаційного притягання F = %.3e Н (або %.8lf Н)\n", F, F);

    return 0;
}